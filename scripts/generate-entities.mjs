import { createHash } from 'node:crypto';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const sourcePath = resolve(root, 'vendor/whatwg/entities.json');
const outputPath = resolve(root, 'src/generated/entities.ts');
const check = process.argv.includes('--check');

function buildGeneratedSource(data, digest) {
  const entries = [];
  let maximumKeyLength = 0;
  const seen = new Map();
  for (const sourceKey of Object.keys(data).sort()) {
    if (!sourceKey.startsWith('&')) throw new Error(`Entity key must start with &: ${sourceKey}`);
    const key = sourceKey.slice(1);
    if (!/^[\x00-\x7F]+$/.test(key)) throw new Error(`Entity key must be ASCII: ${sourceKey}`);
    const replacement = data[sourceKey]?.characters;
    if (typeof replacement !== 'string') throw new Error(`Missing characters for ${sourceKey}`);
    const prior = seen.get(key);
    if (prior !== undefined && prior !== replacement) {
      throw new Error(`Duplicate entity key has conflicting values: ${sourceKey}`);
    }
    seen.set(key, replacement);
    entries.push([key, replacement]);
    maximumKeyLength = Math.max(maximumKeyLength, key.length);
  }

  const map = Object.fromEntries(entries);
  const legacyPrefixes = Object.create(null);
  for (const [key, replacement] of entries) {
    if (key.endsWith(';')) continue;
    for (let length = 1; length <= key.length; length += 1) {
      const prefix = key.slice(0, length);
      if (!(prefix in legacyPrefixes)) legacyPrefixes[prefix] = null;
    }
    legacyPrefixes[key] = replacement;
  }
  const header = '// Generated by scripts/generate-entities.mjs. Do not edit.\n'
    + `// WHATWG entities.json SHA-256: ${digest}\n`;
  const source = `${header}`
    + 'export const ENTITY_MAP: Readonly<Record<string, string>> = Object.freeze('
    + `${JSON.stringify(map)});\n`
    + 'export const LEGACY_ENTITY_PREFIX_MAP: Readonly<Record<string, string | null>> = Object.freeze('
    + `${JSON.stringify(legacyPrefixes)});\n`
    + `export const MAX_ENTITY_KEY_LENGTH = ${maximumKeyLength};\n`;
  return { source, entryCount: entries.length };
}

const bytes = await readFile(sourcePath);
const digest = createHash('sha256').update(bytes).digest('hex');
const data = JSON.parse(bytes.toString('utf8'));
const first = buildGeneratedSource(data, digest);
const second = buildGeneratedSource(data, digest);
if (first.source !== second.source) throw new Error('Entity generation is not deterministic');

if (check) {
  const existing = await readFile(outputPath, 'utf8');
  if (existing !== first.source) throw new Error('src/generated/entities.ts is stale');
} else {
  await mkdir(dirname(outputPath), { recursive: true });
  await writeFile(outputPath, first.source, 'utf8');
}
console.log(
  `${check ? 'Verified' : 'Generated'} ${first.entryCount} entries `
  + `(${digest})`,
);
